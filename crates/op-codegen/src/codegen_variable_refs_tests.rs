//! Design-variable reference tests for the markup targets. The fixture's
//! nodes paint only through `$token`s: a scalar `primary`, a `bg` themed
//! per `mode` (default, first theme value: `light`), a numeric `radius`,
//! and `missing`, which the document does not define.

use crate::tests::empty_doc;
use crate::{Codegen, Compose, Flutter, Html, React, ReactNative, Svelte, SwiftUi, Vue};
use jian_ops_schema::PenDocument;

fn token_doc() -> PenDocument {
    jian_ops_schema::load_str(
        r##"{
          "version":"1.0",
          "themes":{"mode":["light","dark"]},
          "variables":{
            "primary":{"type":"color","value":"#3366ff"},
            "bg":{"type":"color","value":[
              {"value":"#ffffff","theme":{"mode":"light"}},
              {"value":"#111111","theme":{"mode":"dark"}}
            ]},
            "radius":{"type":"number","value":12}
          },
          "children":[
            {"type":"frame","id":"card","width":200,"height":100,"cornerRadius":"$radius",
             "fill":[{"type":"solid","color":"$bg"}],
             "stroke":{"thickness":2,"fill":[{"type":"solid","color":"$primary"}]},
             "children":[
               {"type":"text","id":"title","x":10,"y":10,"width":100,"height":20,
                "content":"Hi","fill":[{"type":"solid","color":"$primary"}]},
               {"type":"rectangle","id":"dot","x":10,"y":40,"width":8,"height":8,
                "fill":[{"type":"solid","color":"$missing"}]}
             ]}
          ]
        }"##,
    )
    .expect("token document")
    .value
}

#[test]
fn react_native_resolves_tokens_to_default_theme_colours() {
    let rn = ReactNative.generate(&token_doc());
    assert!(rn.contains("backgroundColor: 'rgb(255,255,255)'"), "{rn}");
    assert!(rn.contains("color: 'rgb(51,102,255)'"), "{rn}");
    assert!(!rn.contains('$'), "{rn}");
}

#[test]
fn native_targets_keep_token_colours() {
    let doc = token_doc();
    // An unparsed `$token` used to drop the colour entirely.
    let flutter = Flutter.generate(&doc);
    assert!(
        flutter.contains("BoxDecoration(color: Color.fromARGB(255,255,255,255))"),
        "{flutter}"
    );
    let swiftui = SwiftUi.generate(&doc);
    assert!(
        swiftui.contains(
            "Text(\"Hi\").foregroundColor(Color(red: 0.200, green: 0.400, blue: 1.000, opacity: 1.000))"
        ),
        "{swiftui}"
    );
    let compose = Compose.generate(&doc);
    assert!(
        compose.contains(".background(Color(255, 255, 255, 255))"),
        "{compose}"
    );
}

#[test]
fn html_declares_the_design_variables() {
    let html = Html.generate(&token_doc());
    let head = &html[..html.find("</head>").expect("head")];
    assert!(
        head.contains("<style>\n/* Generated by OpenPencil — codegen::CssVariables */\n"),
        "{html}"
    );
    assert!(
        head.contains(":root {\n  --primary: #3366ff;\n  --radius: 12;\n}"),
        "{html}"
    );
    assert!(
        head.contains(":root[data-mode=\"dark\"], .dark {\n  --bg: #111111;\n}"),
        "{html}"
    );
}

#[test]
fn html_without_variables_or_motion_has_no_stylesheet() {
    assert!(!Html.generate(&empty_doc()).contains("<style"));
}

#[test]
fn css_markup_targets_reference_colour_variables() {
    let doc = token_doc();
    for (target, markup) in [
        ("html", Html.generate(&doc)),
        ("vue", Vue.generate(&doc)),
        ("svelte", Svelte.generate(&doc)),
    ] {
        // The fallback is the default theme's value: no `data-mode`
        // selector applies until the page sets one.
        assert!(
            markup.contains(
                ";background:var(--bg, #ffffff);border:2px solid var(--primary, #3366ff)"
            ),
            "{target}: {markup}"
        );
        assert!(
            markup.contains(";color:var(--primary, #3366ff)\">Hi"),
            "{target}: {markup}"
        );
        // Non-colour references and undefined tokens resolve like the
        // canvas: the number, and black for a token nothing defines.
        assert!(markup.contains(";border-radius:12px"), "{target}: {markup}");
        assert!(
            markup.contains(";background:rgb(0,0,0)\""),
            "{target}: {markup}"
        );
        assert!(!markup.contains(":$"), "{target}: {markup}");
    }
}

#[test]
fn react_references_colour_variables_with_their_fallback() {
    let react = React.generate(&token_doc());
    assert!(
        react.contains(
            "background: 'var(--bg, #ffffff)', border: '2px solid var(--primary, #3366ff)', borderRadius: 12"
        ),
        "{react}"
    );
    assert!(
        react.contains("color: 'var(--primary, #3366ff)'"),
        "{react}"
    );
    assert!(!react.contains("'$"), "{react}");
}

#[test]
fn css_variable_blocks_keep_the_original_values() {
    // Only the markup reads the prepared copy; the stylesheet still
    // declares the concrete per-theme values.
    let vue = Vue.generate(&token_doc());
    assert!(
        vue.contains(":root {\n  --primary: #3366ff;\n  --radius: 12;\n}"),
        "{vue}"
    );
    assert!(!vue.contains("--bg: var("), "{vue}");
}
